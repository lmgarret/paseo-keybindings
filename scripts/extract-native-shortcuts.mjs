#!/usr/bin/env node
// Regenerates client/native-shortcuts.ts from an installed Paseo app, so the Keyboard Shortcuts
// table can show Paseo's own shortcuts and flag user bindings that shadow them.
//
//   npm run native:extract                       # /Applications/Paseo.app
//   npm run native:extract -- /path/to/Paseo.app
//
// Run it when bumping requirements.paseo, then review the diff: a new native action that overlaps
// a catalog command fails test/catalog.test.ts.
import fs from "node:fs";
import path from "node:path";

const app = process.argv[2] ?? "/Applications/Paseo.app";
const jsDir = path.join(app, "Contents/Resources/app-dist/_expo/static/js/web");
const bundle = fs
  .readdirSync(jsDir)
  .filter((name) => /^index-.*\.js$/.test(name))
  .map((name) => path.join(jsDir, name))
  .sort((a, b) => fs.statSync(b).size - fs.statSync(a).size)[0];
if (!bundle) throw new Error(`No app bundle in ${jsDir}`);
const plist = fs.readFileSync(path.join(app, "Contents/Info.plist"), "utf8");
const version = /<key>CFBundleShortVersionString<\/key>\s*<string>([^<]+)<\/string>/.exec(plist)?.[1] ?? "unknown";

// Binding objects look like {id:"…",action:"…",combo:"…",when:{…},help:{…}}; read each literal.
const source = fs.readFileSync(bundle, "utf8");
const start = /\{id:"[a-z0-9-]+",action:"[a-z.-]+",combo:"/g;
const bindings = [];
for (let match; (match = start.exec(source)); ) {
  let depth = 0;
  let inString = false;
  let i = match.index;
  for (; i < source.length; i++) {
    const ch = source[i];
    if (inString) {
      if (ch === "\\") i++;
      else if (ch === '"') inString = false;
    } else if (ch === '"') inString = true;
    else if (ch === "{" || ch === "[") depth++;
    else if ((ch === "}" || ch === "]") && --depth === 0) break;
  }
  bindings.push(Function(`return (${source.slice(match.index, i + 1)})`)());
}
if (bindings.length === 0) throw new Error("No shortcut bindings found; the bundle format changed");

const SCOPES = { "message-input": "composer", editable: "text field", terminal: "terminal", other: "outside text fields" };
function note(when) {
  const parts = [];
  const scopes = when.focusScope === undefined ? [] : [when.focusScope].flat();
  if (scopes.length) {
    const all = ["message-input", "editable", "other"].every((s) => scopes.includes(s));
    parts.push(all ? "not in terminal" : `focus: ${scopes.map((s) => SCOPES[s] ?? s).join(" or ")}`);
  }
  if (when.terminal === false && !parts.includes("not in terminal")) parts.push("not in terminal");
  if (when.editable === false) parts.push("not in a text field");
  return parts.join(", ") || undefined;
}

// Our command id: Paseo's action id, except composer actions, which Paseo multiplexes through
// "message-input.action" and a payload kind (exposed as "message-input.<kind>", Paseo's own names).
function command(b) {
  if (b.action === "message-input.action" && b.payload?.kind) return `message-input.${b.payload.kind}`;
  return b.action;
}

// Command args from the payload: { delta } for relative navigation. Index navigation takes
// { index } from the binding, not from the table.
function args(b) {
  if (b.payload?.type === "delta") return { delta: b.payload.delta };
  return undefined;
}

const seen = new Set();
const rows = [];
for (const b of bindings) {
  if (!b.help) continue; // Internal bindings (e.g. dictation confirm on Enter) are not listed by Paseo either.
  const row = { id: b.id, command: command(b), label: b.help.label, combo: b.combo };
  if (row.command !== b.action) row.action = b.action;
  const a = args(b);
  if (a) row.args = a;
  if (b.when?.mac !== undefined) row.mac = b.when.mac;
  if (b.when?.desktopBindings !== undefined) row.desktop = b.when.desktopBindings;
  const n = note(b.when ?? {});
  if (n) row.note = n;
  const id = JSON.stringify(row);
  if (seen.has(id)) continue;
  seen.add(id);
  rows.push(row);
}

const literal = (value) =>
  value !== null && typeof value === "object"
    ? `{ ${Object.entries(value).map(([k, v]) => `${k}: ${literal(v)}`).join(", ")} }`
    : JSON.stringify(value);
const body = rows.map((row) => `  ${literal(row)},`).join("\n");
process.stdout.write(`// Generated by scripts/extract-native-shortcuts.mjs from Paseo ${version}. Do not edit.
// Paseo's built-in shortcuts with their default keys. The plugin exposes each as a command (Paseo's
// implementation runs when it has a key), lists them in the Keyboard Shortcuts table, and reads the
// user's rebinds from Paseo's storage by binding id (see client/paseo-actions.ts).

export interface NativeShortcut {
  /** Paseo binding id; Paseo stores the user's rebinds under it. */
  id: string;
  /** Command id: Paseo's action id, or "message-input.<kind>" for composer actions. */
  command: string;
  /** Paseo's action id when it differs from \`command\`. */
  action?: string;
  label: string;
  /** Default key in Paseo's syntax ("Cmd+Shift+\\\\", "Mod+/", "Alt+Digit"). */
  combo: string;
  /** Command args this binding answers to, e.g. { delta: -1 }. */
  args?: Readonly<Record<string, unknown>>;
  /** Only on macOS (true) or only elsewhere (false). */
  mac?: boolean;
  /** Only in the desktop app (true) or only in a browser (false). */
  desktop?: boolean;
  /** Focus conditions, in words. */
  note?: string;
}

export const NATIVE_SHORTCUTS_VERSION = ${JSON.stringify(version)};

export const NATIVE_SHORTCUTS: readonly NativeShortcut[] = [
${body}
];
`);
